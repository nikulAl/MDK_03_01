# 1. СЛОВАРЬ МОДЕЛЕЙ КЛАССИФИКАЦИИ
# =============================================================================
def classificationModels():
    """
    Инициализирует и возвращает словарь, содержащий популярные модели 
    классификации из библиотек scikit-learn и XGBoost.
    """
    models = {}
    
    ######################################
    # Логистическая регрессия (Logistic Regression)
    ######################################
    # Линейный классификатор, вычисляющий вероятность принадлежности к классу
    from sklearn.linear_model import LogisticRegression
    models['Logistic Regression'] = LogisticRegression()
    
    ######################################
    # Случайный лес (Random Forest Classifier)
    ######################################
    # Ансамблевый метод, строящий множество независимых деревьев решений
    from sklearn.ensemble import RandomForestClassifier
    models['Random Forests'] = RandomForestClassifier()
    
    ######################################
    # Метод K-ближайших соседей (K Nearest Neighbors)
    ######################################
    # Метрический алгоритм, классифицирующий объект по большинству голосов его соседей
    from sklearn.neighbors import KNeighborsClassifier
    models['K Nearest Neighbors'] = KNeighborsClassifier()
    
    ######################################
    # Адаптивный бустинг (AdaBoost)
    ######################################
    # Алгоритм последовательного построения ансамбля, где каждая новая модель
    # исправляет ошибки предыдущих, фокусируясь на сложных объектах
    from sklearn.ensemble import AdaBoostClassifier
    from sklearn.tree import DecisionTreeClassifier
    models['Ada Boost'] = AdaBoostClassifier()
    
    ######################################
    # Экстремальный градиентный бустинг (XGBoost)
    ######################################
    # Высокоэффективная реализация градиентного бустинга над деревьями решений,
    # оптимизированная по скорости и качеству
    from xgboost import XGBClassifier
    models['X Gradient Boosting'] = XGBClassifier()
    
    ######################################
    # Многослойный перцептрон (Нейронная сеть MLP)
    ######################################
    # Полносвязная искусственная нейронная сеть прямого распространения
    from sklearn.neural_network import MLPClassifier
    models['MultiLayer Perceptron'] = MLPClassifier()
    
    return models


# =============================================================================
# 2. СЛОВАРЬ МОДЕЛЕЙ РЕГРЕССИИ
# =============================================================================
def regressionModels():
    """
    Инициализирует и возвращает словарь, содержащий базовые модели 
    регрессии для прогнозирования непрерывных числовых значений.
    """
    models = {}
    
    ######################################
    # Линейная регрессия (Linear Regression)
    ######################################
    # Находит оптимальное линейное уравнение связи между признаками и целевой переменной
    from sklearn.linear_model import LinearRegression
    models['Linear Regression'] = LinearRegression()
    
    ######################################
    # Случайный лес регрессии (Random Forest Regressor)
    ######################################
    # Ансамбль деревьев решений, где итоговый прогноз — это усредненное значение всех деревьев
    from sklearn.ensemble import RandomForestRegressor
    models['Random Forests'] = RandomForestRegressor()
    
    ######################################
    # Метод K-ближайших соседей для регрессии (KNN Regressor)
    ######################################
    # Прогноз рассчитывается как среднее (или взвешенное) значение целевой переменной K ближайших точек
    from sklearn.neighbors import KNeighborsRegressor
    models['K Nearest Neighbors'] = KNeighborsRegressor()
    
    ######################################
    # Адаптивный бустинг для регрессии (AdaBoost Regressor)
    ######################################
    # Последовательный ансамбль слабых регрессоров для минимизации ошибки прогнозирования
    from sklearn.ensemble import AdaBoostRegressor
    from sklearn.tree import DecisionTreeRegressor
    models['AdaBoost'] = AdaBoostRegressor()
    
    ######################################
    # Градиентный бустинг XGBoost для регрессии (XGBRegressor)
    ######################################
    # Мощный алгоритм бустинга, оптимизированный под минимизацию функции потерь в задачах регрессии
    from xgboost import XGBRegressor
    models['X Gradient Boosting'] = XGBRegressor()
    
    ######################################
    # Многослойный перцептрон для регрессии (MLP Regressor)
    ######################################
    # Нейросетевая модель для выявления сложных нелинейных зависимостей в данных
    from sklearn.neural_network import MLPRegressor
    models['MultiLayer Perceptron'] = MLPRegressor()
    
    return models
